import { z } from 'zod';
import { CONTEXT_KEYS } from './context';
import { FIRST_PARTY_MANIFEST } from './firstParty';
import { layoutDocumentSchema } from './layout';
import { blockManifestSchema } from './manifest';

const json = (value: unknown): string => JSON.stringify(value, null, 2);
const schemaOf = (schema: z.ZodType): unknown => {
  const { $schema: _dropped, ...rest } = z.toJSONSchema(schema, { io: 'input', unrepresentable: 'any' }) as Record<string, unknown>;
  return rest;
};

/** `docs/blocks.md`, generated from the manifest and layout schemas. `pnpm blocks-docs` writes it and a unit test compares it. */
export function renderBlocksMarkdown(): string {
  const rows = FIRST_PARTY_MANIFEST.panes.map((pane) => {
    const inputs = 'inputs' in pane ? Object.entries(pane.inputs).map(([name, input]) => `${name} (${input.contextKey})`).join(', ') : '';
    return `| \`${pane.type}\` | ${pane.title} | ${pane.tier} | ${inputs || 'none'} |`;
  });
  return [
    '# Blocks and layouts',
    '',
    'Generated by `pnpm blocks-docs` from `app/src/core/blocks`. Design: `decisions/0020-block-model-and-layout-design.md`.',
    '',
    '## First-party pane types',
    '',
    '| Type | Title | Tier | Inputs |',
    '|---|---|---|---|',
    ...rows,
    '',
    '## Shared context keys',
    '',
    CONTEXT_KEYS.map((key) => `- \`${key}\``).join('\n'),
    '',
    '## Block manifest JSON Schema',
    '',
    '```json',
    json(schemaOf(blockManifestSchema)),
    '```',
    '',
    '## Layout document JSON Schema',
    '',
    '```json',
    json(schemaOf(layoutDocumentSchema)),
    '```',
    '',
  ].join('\n');
}
