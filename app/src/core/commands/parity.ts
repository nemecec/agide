import type { Command } from './types';

export interface ParityRow {
  readonly id: string;
  readonly title: string;
  /** Short text for the UI binding, or `none`. */
  readonly ui: string;
  readonly mcp: boolean;
  /** Whether the tool list that agents receive contains the command. */
  readonly exposed: boolean;
  /** The reason a UI-bound command is not a tool, when the command declares one. */
  readonly exempt?: string;
}

export interface ParityReport {
  readonly rows: readonly ParityRow[];
  /** Commands with a UI binding that agents cannot call. */
  readonly missing: readonly string[];
}

function uiLabel(ui: Command['ui']): string {
  if (ui === false) return 'none';
  const parts = [ui.menu === undefined ? '' : `menu ${ui.menu}`, ui.accelerator === undefined ? '' : `key ${ui.accelerator}`].filter(Boolean);
  return parts.length > 0 ? parts.join(', ') : 'bound';
}

/** `toolNames` is the name list of the MCP tool list as an agent receives it. */
export function checkParity(commands: readonly Command[], toolNames: readonly string[]): ParityReport {
  const exposed = new Set(toolNames);
  const rows = [...commands]
    .sort((a, b) => a.id.localeCompare(b.id))
    .map((command) => ({
      id: command.id,
      title: command.title,
      ui: uiLabel(command.ui),
      mcp: command.mcp,
      exposed: exposed.has(command.id),
      ...(command.mcpExempt === undefined ? {} : { exempt: command.mcpExempt }),
    }));
  const missing = commands
    .filter((command) => command.ui !== false && !exposed.has(command.id) && command.mcpExempt === undefined)
    .map((command) => command.id);
  return { rows, missing };
}

export function renderParityMarkdown(report: ParityReport): string {
  const yesNo = (value: boolean): string => (value ? 'yes' : 'no');
  const lines = [
    '# UI and MCP parity',
    '',
    'Generated by `pnpm parity` from the command registry and the tool list of the app MCP server. Do not edit.',
    'A command with a UI binding must be an MCP tool unless it declares `mcpExempt` with a reason. The check fails otherwise.',
    '',
    '| Command | UI binding | MCP tool | Status |',
    '|---|---|---|---|',
    ...report.rows.map((row) => {
      const status = row.ui === 'none' || row.exposed ? 'ok' : row.exempt === undefined ? 'MISSING' : `exempt: ${row.exempt}`;
      return `| \`${row.id}\` | ${row.ui} | ${yesNo(row.exposed)} | ${status} |`;
    }),
    '',
  ];
  return lines.join('\n');
}
